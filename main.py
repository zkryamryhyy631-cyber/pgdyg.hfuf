    start = page * per_page
    end = min(start+per_page, 100)
    mk = types.InlineKeyboardMarkup(row_width=1)
    for i in range(start, end):
        mk.add(types.InlineKeyboardButton(FULL_NAMES[i], callback_data=f"btn_{i+1}"))
